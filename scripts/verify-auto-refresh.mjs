import assert from 'node:assert/strict';
import { loadChannelFeed, detectShort, parseFeed } from '../netlify/lib/youtube.mjs';
import { matchingVehicles, videoMetadata } from '../netlify/lib/catalogue.mjs';
import { syncPublication } from './sync-publication.mjs';

// Fixture IDs remain in memory and are never written into the real catalogue.
const fixtures=Array.from({length:15},(_,i)=>({id:'testvideo'+String(i).padStart(2,'0'),title:i===0?'2028 Mazda SUV review':'A cabin detail without a Shorts hashtag',published:new Date(Date.UTC(2026,9,2,12,i)).toISOString()}));
const xml='<feed>'+fixtures.map(v=>`<entry><yt:videoId>${v.id}</yt:videoId><title>${v.title}</title><published>${v.published}</published></entry>`).join('')+'</feed>';
let unknown=false;
const fetchImpl=async url=>{
  if(String(url).includes('/feeds/'))return new Response(xml);
  const id=String(url).split('/').pop();
  if(unknown&&id===fixtures[14].id)return new Response(null,{status:302,headers:{location:'https://consent.youtube.com/m?continue=%2Fwatch'}});
  return Number(id.slice(-2))%2===0?new Response(null,{status:302,headers:{location:'/watch?v='+id}}):new Response(null,{status:200});
};
const previous=[{id:'oldvideo001',title:'Older full coverage',published:'2025-01-01T00:00:00Z',isShort:false}];
let feed=await loadChannelFeed({fetchImpl,previous});
assert.equal(feed.latestVideos.length,15,'Do not truncate the RSS list');
assert.equal(feed.archive.length,16,'Keep older saved coverage');
assert.equal(new Set(feed.archive.map(v=>v.id)).size,16);
assert(feed.latestShorts.every(v=>v.isShort===true));
assert(feed.latestLongVideos.every(v=>v.isShort===false));
assert.equal(feed.latestVideos[1].isShort,true,'Short without hashtag uses format probe');
assert.deepEqual(feed.latestVideos[0].makes,['Mazda']);
assert.deepEqual(feed.latestVideos[0].years,['2028']);
assert.deepEqual(feed.latestVideos[0].types,['SUV']);
unknown=true;
feed=await loadChannelFeed({fetchImpl,previous});
assert.equal(feed.latestVideos[14].isShort,null,'Do not guess a format on consent/error');
feed=await loadChannelFeed({fetchImpl,previous:[...previous,{...fixtures[14],isShort:true}]});
assert.equal(feed.latestVideos[14].isShort,true,'Keep confirmed format on a transient failure');
assert.equal(await detectShort(fixtures[0].id,async()=>new Response(null,{status:302,headers:{location:'https://example.test/watch?v='+fixtures[0].id}})),null);
assert.equal(parseFeed('<feed><entry><yt:videoId>testvideo00</yt:videoId><title>bad date</title><published>invalid</published></entry></feed>').length,0);
assert.doesNotThrow(()=>parseFeed(xml.replace('2028 Mazda SUV review','Bad &#99999999; entity')));
const vehicles=[{slug:'camry',year:2026,make:'Toyota',model:'Camry XSE AWD',type:'Sedan'}];
assert.equal(matchingVehicles('2026 Toyota Camry LE review',vehicles).length,0,'Do not guess XSE AWD from base model');
assert.equal(matchingVehicles('2026 Toyota Camry XSE AWD review',vehicles).length,1);
assert.deepEqual(videoMetadata('Is this red interior too much?'),{makes:[],years:[],types:[]});
const data={vehicles,videos:[],contentChecked:'2026-01-01'},provenance=[];
let result=syncPublication(data,feed,provenance,new Date('2026-10-02T12:00:00Z'));
assert.equal(result.added,16);assert.equal(provenance.length,16);
assert(data.videos.find(v=>v.id===fixtures[0].id).makes.includes('Mazda'));
const snapshot=JSON.stringify(data);
result=syncPublication(data,feed,provenance,new Date('2026-10-03T12:00:00Z'));
assert.equal(result.added,0);assert.equal(result.changed,false);assert.equal(JSON.stringify(data),snapshot,'No deploy for unchanged content');
const renamed={...fixtures[0],title:'2029 Honda SUV updated review',isShort:true};
const entry=data.videos.find(v=>v.id===renamed.id),slug=entry.slug;
syncPublication(data,{latestVideos:[renamed]},provenance);
assert.equal(entry.slug,slug,'Stable companion URL after title edits');
assert.equal(entry.title,renamed.title);assert.equal(entry.format,'short');assert.deepEqual(entry.makes,['Honda']);assert.deepEqual(entry.years,['2029']);
syncPublication(data,{latestVideos:[{...renamed,isShort:null}]},provenance);
assert.equal(entry.format,'short','Do not downgrade confirmed publication format');
entry.automatic=false;entry.title='Curated editorial title';
syncPublication(data,{latestVideos:[{...renamed,title:'New source title'}]},provenance);
assert.equal(entry.title,'Curated editorial title');assert.equal(entry.originalTitle,'New source title');
console.log('Automatic refresh checks passed: full feed, archive retention, format probes, unknown formats, title updates, safe vehicle matching, new filter values and idempotent publication.');
